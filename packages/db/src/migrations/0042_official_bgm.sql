CREATE TABLE official_bgm (
  id CHAR(36) CHARACTER SET ascii NOT NULL,
  source_key VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  title VARCHAR(120) NOT NULL,
  genre VARCHAR(24) NOT NULL,
  scenario VARCHAR(24) NOT NULL,
  mood VARCHAR(24) NOT NULL,
  master_key VARCHAR(255) CHARACTER SET ascii NOT NULL,
  master_ms INT UNSIGNED NOT NULL,
  preview_key VARCHAR(255) CHARACTER SET ascii NOT NULL,
  preview_start_ms INT UNSIGNED NOT NULL,
  preview_ms INT UNSIGNED NOT NULL,
  state VARCHAR(16) NOT NULL DEFAULT 'draft',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  published_at DATETIME(3) NULL,
  PRIMARY KEY (id),
  UNIQUE KEY official_bgm_source_uk (source_key),
  UNIQUE KEY official_bgm_sha_uk (sha256),
  KEY official_bgm_public_idx (state, published_at, id),
  CONSTRAINT official_bgm_state_chk CHECK (state IN ('draft','reviewed','published','archived')),
  CONSTRAINT official_bgm_publish_chk CHECK ((state = 'published') = (published_at IS NOT NULL)),
  CONSTRAINT official_bgm_media_chk CHECK (master_ms >= 60000 AND preview_ms BETWEEN 1000 AND 60000)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
