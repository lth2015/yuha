#!/usr/bin/env node
/**
 * Generates the demo audio fixtures.
 *
 * PROJECT_TASK.md M1 requires "自有测试音频" — audio we own outright. Rather
 * than shipping sample files of uncertain provenance, every fixture is
 * synthesised here from scratch with ffmpeg oscillators and noise generators.
 * There is no third-party recording, sample or model output involved, so the
 * demo path carries no licensing question at all.
 *
 * These are obviously synthetic tones. They exist to prove the engineering
 * pipeline (duration, encoding, trimming, checksums, delivery). §8 is explicit
 * that they prove nothing about model quality or musical value.
 */
import { spawn } from 'node:child_process';
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'assets', 'fixtures', 'audio');

/** One fixture per supported song length, so the duration check is exact. */
const DURATIONS = [30, 60, 120, 180, 240];

/**
 * Each fixture is a small additive-synthesis patch: a chord pad, a bass pulse
 * and a filtered-noise percussion layer, mixed and given a gentle envelope.
 */
const FIXTURES = [
  {
    name: 'night_walk_calm',
    label: '夜の散歩 / calm',
    chord: [220.0, 277.18, 329.63], // A minor-ish pad
    bass: 55.0,
    bpm: 76,
    noiseGain: 0.05,
    lowpass: 2200,
  },
  {
    name: 'night_walk_dreamy',
    label: '夜景 / dreamy',
    chord: [261.63, 329.63, 392.0],
    bass: 65.41,
    bpm: 84,
    noiseGain: 0.04,
    lowpass: 3000,
  },
  {
    name: 'daily_log_warm',
    label: '日常記録 / warm',
    chord: [293.66, 369.99, 440.0],
    bass: 73.42,
    bpm: 96,
    noiseGain: 0.07,
    lowpass: 4200,
  },
  {
    name: 'outfit_confident',
    label: 'コーデ / confident',
    chord: [329.63, 415.3, 493.88],
    bass: 82.41,
    bpm: 108,
    noiseGain: 0.1,
    lowpass: 6000,
  },
  {
    name: 'gaming_tense',
    label: 'ゲーム / tense',
    chord: [246.94, 311.13, 369.99],
    bass: 61.74,
    bpm: 128,
    noiseGain: 0.12,
    lowpass: 7000,
  },
];

function buildFilter(f, duration) {
  const beat = 60 / f.bpm;
  const inputs = [];
  const chain = [];

  f.chord.forEach((freq, i) => {
    inputs.push(`sine=frequency=${freq}:duration=${duration}`);
    // Slow tremolo per voice, slightly detuned in rate so the pad breathes.
    chain.push(`[${i}:a]volume=0.16,tremolo=f=${(0.18 + i * 0.05).toFixed(2)}:d=0.35[p${i}]`);
  });

  const bassIdx = f.chord.length;
  inputs.push(`sine=frequency=${f.bass}:duration=${duration}`);
  // Gate the bass into a pulse on the beat.
  chain.push(
    `[${bassIdx}:a]volume=0.35,` +
      `apulsator=hz=${(1 / beat).toFixed(4)}:amount=0.9,` +
      `lowpass=f=180[bass]`,
  );

  const noiseIdx = bassIdx + 1;
  inputs.push(`anoisesrc=color=brown:duration=${duration}:amplitude=0.6`);
  chain.push(
    `[${noiseIdx}:a]volume=${f.noiseGain},` +
      `apulsator=hz=${(2 / beat).toFixed(4)}:amount=1,` +
      `highpass=f=900,lowpass=f=${f.lowpass}[perc]`,
  );

  const padLabels = f.chord.map((_, i) => `[p${i}]`).join('');
  chain.push(
    `${padLabels}[bass][perc]amix=inputs=${f.chord.length + 2}:normalize=0,` +
      `lowpass=f=${f.lowpass},` +
      `afade=t=in:st=0:d=1.5,afade=t=out:st=${Math.max(duration - 2, 0.5)}:d=2,` +
      `loudnorm=I=-16:TP=-1.5:LRA=11[out]`,
  );

  return { inputs, filter: chain.join(';') };
}

function run(args) {
  return new Promise((resolve, reject) => {
    const child = spawn('ffmpeg', args, { stdio: ['ignore', 'ignore', 'pipe'] });
    let stderr = '';
    child.stderr.on('data', (d) => (stderr += d.toString()));
    child.on('error', reject);
    child.on('close', (code) =>
      code === 0 ? resolve() : reject(new Error(`ffmpeg exited ${code}: ${stderr.slice(-800)}`)),
    );
  });
}

async function main() {
  await mkdir(outDir, { recursive: true });
  let count = 0;
  for (const f of FIXTURES) {
    for (const duration of DURATIONS) {
      const { inputs, filter } = buildFilter(f, duration);
      const args = ['-hide_banner', '-v', 'error', '-y'];
      for (const i of inputs) args.push('-f', 'lavfi', '-i', i);
      args.push(
        '-filter_complex', filter,
        '-map', '[out]',
        '-t', String(duration),
        '-codec:a', 'libmp3lame',
        '-b:a', '192k',
        '-ar', '44100',
        '-ac', '2',
        '-map_metadata', '-1',
        '-metadata', 'title=YUHA demo fixture (synthetic, not a real generation)',
        '-metadata', 'comment=Synthesised by scripts/make-audio-fixtures.mjs. Demo use only.',
        join(outDir, `${f.name}-${duration}s.mp3`),
      );
      await run(args);
      count += 1;
    }
    console.log(`  ✓ ${f.name}-{${DURATIONS.join(',')}}s.mp3  (${f.label})`);
  }

  await writeFile(
    join(outDir, 'PROVENANCE.md'),
    [
      '# Demo audio fixture provenance',
      '',
      'Every file in this directory is generated by `scripts/make-audio-fixtures.mjs`',
      'using ffmpeg oscillators and noise sources. There is no third-party recording,',
      'sample, or AI model output in any of them, so they carry no external licence',
      'obligation and can be used for demonstration freely.',
      '',
      'They are synthetic tones, not music produced by a music model. They demonstrate',
      'the engineering pipeline only, and are not evidence of model quality,',
      'originality, or commercial value.',
      '',
      `Generated: ${new Date().toISOString()}`,
      `Durations: ${DURATIONS.join('s, ')}s each, MP3 192 kbps, 44.1 kHz stereo.`,
      '',
      '| character | files |',
      '| --- | --- |',
      ...FIXTURES.map((f) => `| ${f.label} | ${f.name}-{30,60,120,180,240}s.mp3 |`),
      '',
    ].join('\n'),
    'utf8',
  );

  console.log(`\nWrote ${count} fixtures to ${outDir}`);
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
